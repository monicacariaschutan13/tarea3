    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if (Indice <5){
            String Nombre = txtNombre.getText();
            Pasajeros [Indice] = Nombre;
            txtLista.append ((Indice + 1)+ "." + Nombre + "/n");
            Indice++;
            txtNombre.setText("");
    JOptionPane.showMessageDialog(null, "Pasajero Registrado (" + Indice + " /5)");
        } else {
    JOptionPane.showMessageDialog(null,"Ya ingresó los 5 pasajeros");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
        try{
            FileWriter fw = new
                FileWriter ("monica_manifiesto.txt");
            try (PrintWriter pw = new PrintWriter (fw)) {
                pw.println("Manifiesto Oficial de Vuelo");
                for (int i = 0; i < 5; i++){
                    pw.println ((i + 1)+ "." + Pasajeros [i]);
                }
            }
    JOptionPane.showMessageDialog(null, "Manifiesto exportado con éxito");
        } catch (HeadlessException | IOException e){
    JOptionPane.showMessageDialog(null, "Error al crear el archivo");
        }
    }//GEN-LAST:event_btnExportarActionPerformed

